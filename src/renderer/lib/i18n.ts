export type Lang = 'tr' | 'en';
export type Key = keyof typeof dict;

export function t(key: Key, lang: Lang = useAppStore.getState().lang, vars?: Record<string, string | number>): string {
  const pair = dict[key];
  let s: string = pair ? pair[lang === 'tr' ? 0 : 1] : key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function useT() {
  const lang = useAppStore((s) => s.lang);
  return (key: Key, vars?: Record<string, string | number>) => t(key, lang, vars);
}
